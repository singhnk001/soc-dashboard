import { NextResponse } from 'next/server';

export async function GET(
  request: Request,
  { params }: { params: Promise<{ alertId: string }> }
) {
  const { alertId } = await params;
  const apiUrl = process.env.NEXT_PUBLIC_API_URL || 'http://127.0.0.1:8002';

  try {
    const res = await fetch(`${apiUrl}/api/alerts/${alertId}/comments`, {
      signal: AbortSignal.timeout(3000),
      cache: 'no-store',
    });
    if (res.ok) {
      return NextResponse.json(await res.json());
    }
  } catch {}

  // Local fallback if backend unavailable
  return NextResponse.json({
    data: [
      {
        id: 'c-01',
        alert_id: alertId,
        user: 'System',
        comment: 'Alert generated by correlation engine. Triage initiated.',
        created_at: new Date(Date.now() - 3600 * 1000).toISOString(),
      },
    ],
  });
}

export async function POST(
  request: Request,
  { params }: { params: Promise<{ alertId: string }> }
) {
  const { alertId } = await params;
  const body = await request.json();
  const apiUrl = process.env.NEXT_PUBLIC_API_URL || 'http://127.0.0.1:8002';

  try {
    const res = await fetch(`${apiUrl}/api/alerts/${alertId}/comments`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(4000),
    });
    if (res.ok) {
      return NextResponse.json(await res.json());
    }
  } catch {}

  return NextResponse.json({ status: 'success', id: `c-${Date.now()}` });
}
